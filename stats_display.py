#!/usr/bin/env python3
"""
PhishGuard dataset/training statistics viewer.

Reads the artifacts generated by dataset_manager.py. If training_history.csv
and test_metrics.json exist in the artifact directory, it also plots model
training curves and displays test metrics.

Expected optional training_history.csv columns:
    epoch, train_loss, val_loss, val_accuracy, val_f1, val_auc

Expected optional test_metrics.json:
    {"accuracy": ..., "precision": ..., "recall": ..., "f1": ..., "roc_auc": ...}

Usage:
    python stats_display.py --artifacts ./phishguard_artifacts
"""

import argparse
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


def main():
    parser = argparse.ArgumentParser(description="Display PhishGuard statistics.")
    parser.add_argument("--artifacts", default="phishguard_artifacts")
    args = parser.parse_args()

    root = Path(args.artifacts).expanduser().resolve()
    report_path = root / "dataset_report.json"
    if not report_path.exists():
        raise FileNotFoundError(
            f"{report_path} not found. Run dataset_manager.py first."
        )

    report = json.loads(report_path.read_text(encoding="utf-8"))

    print("\n========== DATASET SUMMARY ==========")
    print("Source:", report["source_csv"])
    print("Rows after cleaning:", report["rows_after_cleaning"])
    print("Processed input dimensions:", report["processed_feature_count"])

    print("\n========== SPLITS ==========")
    for name, shape in report["split_shapes"].items():
        print(f"{name:12s}: {shape[0]:,} samples x {shape[1]} features")

    print("\n========== CLASS COUNTS ==========")
    for split, counts in report["class_counts"].items():
        print(f"\n{split.capitalize()}")
        for label, count in counts.items():
            class_name = "Legitimate" if label == "0" else "Phishing"
            print(f"  {class_name:12s}: {count:,}")

    print("\n========== DOMAIN OVERLAP ==========")
    for pair, count in report["domain_overlap"].items():
        print(f"{pair:20s}: {count}")

    # Plot class counts across the three partitions.
    split_names = list(report["class_counts"].keys())
    legitimate = [report["class_counts"][s].get("0", 0) for s in split_names]
    phishing = [report["class_counts"][s].get("1", 0) for s in split_names]

    x = np.arange(len(split_names))
    width = 0.36
    fig, ax = plt.subplots(figsize=(8, 5))
    ax.bar(x - width / 2, legitimate, width, label="Legitimate")
    ax.bar(x + width / 2, phishing, width, label="Phishing")
    ax.set_xticks(x, [s.capitalize() for s in split_names])
    ax.set_ylabel("Samples")
    ax.set_title("PhishGuard Dataset Class Distribution")
    ax.legend()
    ax.grid(axis="y", alpha=0.25)
    plt.tight_layout()
    plt.show()

    # Optional training curves.
    history_path = root / "training_history.csv"
    if history_path.exists():
        history = pd.read_csv(history_path)
        if {"epoch", "train_loss", "val_loss"}.issubset(history.columns):
            fig, ax = plt.subplots(figsize=(8, 5))
            ax.plot(history["epoch"], history["train_loss"], label="Train loss")
            ax.plot(history["epoch"], history["val_loss"], label="Validation loss")
            ax.set_xlabel("Epoch")
            ax.set_ylabel("Loss")
            ax.set_title("Training and Validation Loss")
            ax.legend()
            ax.grid(alpha=0.25)
            plt.tight_layout()
            plt.show()

        for column, title in [
            ("val_accuracy", "Validation Accuracy"),
            ("val_f1", "Validation F1"),
            ("val_auc", "Validation ROC-AUC"),
        ]:
            if {"epoch", column}.issubset(history.columns):
                fig, ax = plt.subplots(figsize=(8, 4))
                ax.plot(history["epoch"], history[column])
                ax.set_xlabel("Epoch")
                ax.set_ylabel(column)
                ax.set_title(title)
                ax.grid(alpha=0.25)
                plt.tight_layout()
                plt.show()
    else:
        print("\nNo training_history.csv found; skipping training curves.")

    # Optional final test metrics.
    metrics_path = root / "test_metrics.json"
    if metrics_path.exists():
        metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
        print("\n========== TEST METRICS ==========")
        for name, value in metrics.items():
            if isinstance(value, (float, int)):
                print(f"{name:12s}: {value:.4f}")
            else:
                print(f"{name:12s}: {value}")
    else:
        print("No test_metrics.json found; skipping test metric summary.")


if __name__ == "__main__":
    main()
